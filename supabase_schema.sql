-- View: tóm tắt vi phạm theo video
-- ============================================================
DROP VIEW IF EXISTS public.video_violation_summary;
CREATE OR REPLACE VIEW video_violation_summary AS
SELECT
    v.id,
    v.file_name,
    v.file_url,
    v.upload_by,
    v.upload_time,
    v.status,
    v.violation_count,
    COUNT(vi.id) FILTER (WHERE vi.violation_type = 'no_helmet')             AS no_helmet_count,
    COUNT(vi.id) FILTER (WHERE vi.violation_type = 'overloaded_motorcycle') AS overloaded_count,
    COUNT(vi.id) FILTER (WHERE vi.violation_type = 'red_light')              AS red_light_count
FROM videos v
LEFT JOIN violations vi ON vi.video_id = v.id
GROUP BY v.id;

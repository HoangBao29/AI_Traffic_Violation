-- Repair timestamps from legacy image/video records so sorting and trends include old violations.
UPDATE public.violations AS violation
SET created_at = COALESCE(
    (SELECT analysis.created_at
     FROM public.image_analyses AS analysis
     WHERE analysis.id = violation.image_analysis_id),
    (SELECT video.upload_time
     FROM public.videos AS video
     WHERE video.id = violation.video_id),
    NOW()
)
WHERE violation.created_at IS NULL;

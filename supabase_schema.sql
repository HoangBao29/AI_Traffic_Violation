CREATE OR REPLACE FUNCTION public.claim_next_video_job()
RETURNS SETOF public.videos
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    UPDATE public.videos
    SET status = CASE
            WHEN processing_attempts >= 3 THEN 'error'
            ELSE 'pending'
        END,
        processing_error = CASE
            WHEN processing_attempts >= 3 THEN COALESCE(processing_error, 'Worker stopped before finishing.')
            ELSE processing_error
        END
    WHERE status = 'processing'
      AND updated_at < NOW() - INTERVAL '30 minutes';

    RETURN QUERY
    WITH next_job AS (
        SELECT id
        FROM public.videos
        WHERE status = 'pending'
          AND processing_attempts < 3
        ORDER BY id
        FOR UPDATE SKIP LOCKED
        LIMIT 1
    )
    UPDATE public.videos AS video
    SET status = 'processing',
        processing_attempts = video.processing_attempts + 1,
        processing_progress = 0,
        processing_error = NULL
    FROM next_job
    WHERE video.id = next_job.id
    RETURNING video.*;
END;
$$;

REVOKE ALL ON FUNCTION public.claim_next_video_job() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.claim_next_video_job() TO service_role;

CREATE OR REPLACE FUNCTION public.violation_trends(
    p_start_date DATE,
    p_end_date DATE,
    p_bucket TEXT DEFAULT 'day'
)
RETURNS TABLE(bucket_start DATE, violation_type TEXT, violation_count BIGINT)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    WITH buckets AS (
        SELECT generate_series(
            date_trunc(p_bucket, p_start_date::TIMESTAMP)::DATE,
            date_trunc(p_bucket, p_end_date::TIMESTAMP)::DATE,
            CASE WHEN p_bucket = 'week' THEN INTERVAL '1 week' ELSE INTERVAL '1 day' END
        )::DATE AS bucket_start
    ),
    types(violation_type) AS (
        VALUES ('no_helmet'), ('overloaded_motorcycle'), ('red_light')
    ),
    counts AS (
        SELECT
            date_trunc(p_bucket, created_at)::DATE AS bucket_start,
            violations.violation_type,
            COUNT(*) AS violation_count
        FROM public.violations
        WHERE created_at >= p_start_date::TIMESTAMPTZ
          AND created_at < (p_end_date + 1)::TIMESTAMPTZ
        GROUP BY 1, 2
    )
    SELECT buckets.bucket_start, types.violation_type,
           COALESCE(counts.violation_count, 0)::BIGINT
    FROM buckets
    CROSS JOIN types
    LEFT JOIN counts USING (bucket_start, violation_type)
    ORDER BY buckets.bucket_start, types.violation_type;
$$;

REVOKE ALL ON FUNCTION public.violation_trends(DATE, DATE, TEXT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.violation_trends(DATE, DATE, TEXT) TO service_role;

-- Trigger tự động cập nhật updated_at
CREATE OR REPLACE FUNCTION update_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_videos_updated_at ON videos;
CREATE TRIGGER trg_videos_updated_at
    BEFORE UPDATE ON videos
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();


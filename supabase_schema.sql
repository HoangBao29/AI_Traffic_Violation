-- Bảng violations: lưu từng vi phạm phát hiện được
CREATE TABLE IF NOT EXISTS violations (
    id          SERIAL PRIMARY KEY,
    video_id    INTEGER REFERENCES videos(id) ON DELETE CASCADE,
    violation_type TEXT NOT NULL
                CHECK (violation_type IN ('no_helmet', 'overloaded_motorcycle', 'red_light')),
    label       TEXT NOT NULL,
    confidence  FLOAT DEFAULT 0,
    frame_number INTEGER,
    box         TEXT,      -- JSON string của [x1, y1, x2, y2]
    extra_data  TEXT,      -- dữ liệu bổ sung (số người, v.v.)
    created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- Nâng cấp các bảng đã được tạo bởi phiên bản schema cũ.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'videos' AND column_name = 'filename'
    ) AND NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'videos' AND column_name = 'file_name'
    ) THEN
        ALTER TABLE public.videos RENAME COLUMN filename TO file_name;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'videos' AND column_name = 'filepath'
    ) THEN
        ALTER TABLE public.videos ALTER COLUMN filepath SET DEFAULT '';
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'violations' AND column_name = 'type'
    ) AND NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'violations' AND column_name = 'violation_type'
    ) THEN
        ALTER TABLE public.violations RENAME COLUMN type TO violation_type;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'violations' AND column_name = 'frame_index'
    ) AND NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'violations' AND column_name = 'frame_number'
    ) THEN
        ALTER TABLE public.violations RENAME COLUMN frame_index TO frame_number;
    END IF;
END;
$$;

